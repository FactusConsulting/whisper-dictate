//! Behavioral coverage for `scripts/ci/version-only-change.sh`, the CI gate
//! that lets a pure release-version bump skip the heavy test legs.
#![cfg(target_os = "linux")]

mod common;

use std::fs;
use std::os::unix::fs::PermissionsExt;
use std::path::Path;
use std::process::{Command, Output};

use tempfile::TempDir;

/// Release-version files at `version`, shaped like the real ones: other
/// `version = ` lines (dependencies, other locked packages, the lockfile
/// format) must stay outside the allowed set.
fn release_files(version: &str) -> [(&'static str, String); 4] {
    [
        ("VERSION", format!("{version}\n")),
        (
            "src/rust/Cargo.toml",
            format!(
                "[package]\nname = \"whisper-dictate-app\"\nversion = \"{version}\"\nedition = \"2021\"\n\n\
                 [dependencies]\nserde = {{ version = \"1.0.0\", features = [\"derive\"] }}\n\n\
                 [dependencies.regex]\nversion = \"1.10.0\"\n"
            ),
        ),
        (
            "src/rust/Cargo.lock",
            format!(
                "# This file is automatically @generated by Cargo.\nversion = 4\n\n\
                 [[package]]\nname = \"regex\"\nversion = \"1.10.0\"\n\n\
                 [[package]]\nname = \"whisper-dictate-app\"\nversion = \"{version}\"\ndependencies = [\n \"regex\",\n]\n"
            ),
        ),
        (
            "nix/package.nix",
            format!(
                "{{ lib\n, rustPlatform\n, version ? \"{version}\"\n}}:\n\n\
                 rustPlatform.buildRustPackage {{\n  pname = \"whisper-dictate\";\n  inherit version;\n}}\n"
            ),
        ),
    ]
}

struct Repo {
    dir: TempDir,
}

impl Repo {
    /// A repository whose first commit holds the release files at `version`
    /// plus one source file.
    fn at(version: &str) -> (Self, String) {
        let repo = Self {
            dir: tempfile::tempdir().expect("temp repo"),
        };
        repo.git(&["init", "-q"]);
        repo.write_release(version);
        repo.write(
            "src/rust/src/lib.rs",
            "pub fn answer() -> u32 {\n    42\n}\n",
        );
        let base = repo.commit();
        (repo, base)
    }

    fn git(&self, args: &[&str]) -> String {
        let output = isolated_git(self.dir.path())
            .args(args)
            .output()
            .expect("run git");
        assert!(
            output.status.success(),
            "git {args:?} failed: {}",
            String::from_utf8_lossy(&output.stderr)
        );
        String::from_utf8(output.stdout).expect("git stdout is UTF-8")
    }

    fn write(&self, relative: &str, contents: &str) {
        let path = self.dir.path().join(relative);
        fs::create_dir_all(path.parent().expect("file parent")).expect("create parent");
        fs::write(path, contents).expect("write fixture file");
    }

    fn read(&self, relative: &str) -> String {
        fs::read_to_string(self.dir.path().join(relative)).expect("read fixture file")
    }

    fn write_release(&self, version: &str) {
        for (relative, contents) in release_files(version) {
            self.write(relative, &contents);
        }
    }

    fn replace(&self, relative: &str, from: &str, to: &str) {
        let contents = self.read(relative);
        assert!(contents.contains(from), "{relative} lacks {from:?}");
        self.write(relative, &contents.replacen(from, to, 1));
    }

    fn commit(&self) -> String {
        self.git(&["add", "-A"]);
        self.git(&["commit", "-q", "--allow-empty", "-m", "fixture"]);
        self.git(&["rev-parse", "HEAD"]).trim().to_owned()
    }

    fn run(&self, base: &str, head: &str) -> Output {
        let mut command = Command::new("bash");
        command
            .arg(common::repo_root().join("scripts/ci/version-only-change.sh"))
            .args([base, head])
            .current_dir(self.dir.path());
        isolate_git_config(&mut command);
        command.output().expect("run version-only-change.sh")
    }

    /// The script's stdout verdict for `base..head`; the script must succeed.
    fn verdict(&self, base: &str, head: &str) -> String {
        let output = self.run(base, head);
        assert!(
            output.status.success(),
            "version-only-change.sh failed: {}",
            String::from_utf8_lossy(&output.stderr)
        );
        String::from_utf8(output.stdout)
            .expect("verdict is UTF-8")
            .trim()
            .to_owned()
    }

    fn assert_version_only(&self, base: &str, head: &str, case: &str) {
        assert_eq!(self.verdict(base, head), "true", "{case}");
    }

    fn assert_not_version_only(&self, base: &str, head: &str, case: &str) {
        assert_eq!(self.verdict(base, head), "false", "{case}");
    }
}

/// Keeps the developer's global git config (signing, external diff, colour)
/// and any inherited repository selection (dev-check exports `GIT_DIR` and
/// `GIT_WORK_TREE` for the mounted checkout) out of both the fixture commits
/// and the script under test.
fn isolate_git_config(command: &mut Command) {
    for inherited in [
        "GIT_DIR",
        "GIT_WORK_TREE",
        "GIT_INDEX_FILE",
        "GIT_COMMON_DIR",
        "GIT_OBJECT_DIRECTORY",
        "GIT_ALTERNATE_OBJECT_DIRECTORIES",
        "GIT_CONFIG_COUNT",
        "GIT_CONFIG_PARAMETERS",
    ] {
        command.env_remove(inherited);
    }
    command
        .env("GIT_CONFIG_GLOBAL", "/dev/null")
        .env("GIT_CONFIG_NOSYSTEM", "1")
        .env("GIT_AUTHOR_NAME", "ci")
        .env("GIT_AUTHOR_EMAIL", "ci@example.invalid")
        .env("GIT_COMMITTER_NAME", "ci")
        .env("GIT_COMMITTER_EMAIL", "ci@example.invalid");
}

fn isolated_git(cwd: &Path) -> Command {
    let mut command = Command::new("git");
    command.current_dir(cwd);
    isolate_git_config(&mut command);
    command
}

#[test]
fn a_pure_release_bump_is_version_only() {
    let (repo, base) = Repo::at("3.5.1");
    repo.write_release("3.5.2");
    let head = repo.commit();
    repo.assert_version_only(&base, &head, "3.5.1 -> 3.5.2");
}

#[test]
fn release_candidate_bumps_are_version_only() {
    let (repo, stable) = Repo::at("3.5.2");
    repo.write_release("3.6.0-rc.1");
    let rc1 = repo.commit();
    repo.write_release("3.6.0-rc.2");
    let rc2 = repo.commit();
    repo.write_release("3.6.0");
    let final_release = repo.commit();

    repo.assert_version_only(&stable, &rc1, "stable -> rc.1");
    repo.assert_version_only(&rc1, &rc2, "rc.1 -> rc.2");
    repo.assert_version_only(&rc2, &final_release, "rc.2 -> stable");
    repo.assert_version_only(&stable, &final_release, "multi-commit push of bumps");
}

#[test]
fn a_crlf_lockfile_bump_is_version_only() {
    let (repo, _) = Repo::at("3.5.1");
    let crlf = repo.read("src/rust/Cargo.lock").replace('\n', "\r\n");
    repo.write("src/rust/Cargo.lock", &crlf);
    let base = repo.commit();
    repo.replace(
        "src/rust/Cargo.lock",
        "name = \"whisper-dictate-app\"\r\nversion = \"3.5.1\"",
        "name = \"whisper-dictate-app\"\r\nversion = \"3.5.2\"",
    );
    let head = repo.commit();
    repo.assert_version_only(&base, &head, "CRLF Cargo.lock bump");
}

#[test]
fn a_bump_plus_another_file_is_not_version_only() {
    let (repo, base) = Repo::at("3.5.1");
    repo.write_release("3.5.2");
    repo.write(
        "src/rust/src/lib.rs",
        "pub fn answer() -> u32 {\n    43\n}\n",
    );
    let modified = repo.commit();
    repo.assert_not_version_only(&base, &modified, "bump + source edit");

    let (repo, base) = Repo::at("3.5.1");
    repo.write_release("3.5.2");
    repo.write(".github/workflows/test.yml", "name: tests\n");
    let added = repo.commit();
    repo.assert_not_version_only(&base, &added, "bump + new workflow");

    let (repo, base) = Repo::at("3.5.1");
    repo.write_release("3.5.2");
    repo.git(&["rm", "-q", "src/rust/src/lib.rs"]);
    let deleted = repo.commit();
    repo.assert_not_version_only(&base, &deleted, "bump + deleted source");
}

#[test]
fn a_bump_plus_another_line_in_a_version_file_is_not_version_only() {
    let extra_edits = [
        (
            "src/rust/Cargo.toml",
            "[dependencies.regex]\nversion = \"1.10.0\"",
            "[dependencies.regex]\nversion = \"1.11.0\"",
        ),
        (
            "src/rust/Cargo.toml",
            "edition = \"2021\"",
            "edition = \"2024\"",
        ),
        (
            "src/rust/Cargo.lock",
            "name = \"regex\"\nversion = \"1.10.0\"",
            "name = \"regex\"\nversion = \"1.11.0\"",
        ),
        (
            "src/rust/Cargo.lock",
            " \"regex\",\n",
            " \"regex\",\n \"serde\",\n",
        ),
        (
            "nix/package.nix",
            "inherit version;",
            "inherit version;\n  doCheck = false;",
        ),
        ("VERSION", "3.5.2\n", "3.5.2\n3.5.3\n"),
    ];
    for (relative, from, to) in extra_edits {
        let (repo, base) = Repo::at("3.5.1");
        repo.write_release("3.5.2");
        repo.replace(relative, from, to);
        let head = repo.commit();
        repo.assert_not_version_only(&base, &head, &format!("bump + {relative}: {to:?}"));
    }
}

#[test]
fn version_lines_of_other_packages_are_not_release_versions() {
    let (repo, base) = Repo::at("3.5.1");
    repo.replace(
        "src/rust/Cargo.toml",
        "[dependencies.regex]\nversion = \"1.10.0\"",
        "[dependencies.regex]\nversion = \"1.11.0\"",
    );
    repo.replace(
        "src/rust/Cargo.lock",
        "name = \"regex\"\nversion = \"1.10.0\"",
        "name = \"regex\"\nversion = \"1.11.0\"",
    );
    let head = repo.commit();
    repo.assert_not_version_only(&base, &head, "dependency version change");
}

#[test]
fn malformed_versions_are_not_version_only() {
    for version in ["3.5.2-beta.1", "v3.5.2", "3.5", "03.5.2", "3.5.2-rc.0"] {
        let (repo, base) = Repo::at("3.5.1");
        repo.write_release(version);
        let head = repo.commit();
        repo.assert_not_version_only(&base, &head, version);
    }
}

#[test]
fn mode_and_end_of_file_changes_are_not_version_only() {
    let (repo, base) = Repo::at("3.5.1");
    repo.write_release("3.5.2");
    let version_file = repo.dir.path().join("VERSION");
    fs::set_permissions(&version_file, fs::Permissions::from_mode(0o755)).expect("chmod VERSION");
    let mode = repo.commit();
    repo.assert_not_version_only(&base, &mode, "bump + executable VERSION");

    let (repo, base) = Repo::at("3.5.1");
    repo.write_release("3.5.2");
    let toml = repo.read("src/rust/Cargo.toml");
    repo.write("src/rust/Cargo.toml", toml.trim_end_matches('\n'));
    let newline = repo.commit();
    repo.assert_not_version_only(&base, &newline, "bump + dropped final newline");
}

#[test]
fn an_empty_diff_is_not_version_only() {
    let (repo, base) = Repo::at("3.5.1");
    let empty = repo.commit();
    repo.assert_not_version_only(&base, &empty, "empty commit");
    repo.assert_not_version_only(&base, &base, "same commit");
}

#[test]
fn an_unknown_commit_fails_instead_of_answering() {
    let (repo, base) = Repo::at("3.5.1");
    let output = repo.run("0123456789012345678901234567890123456789", &base);
    assert!(!output.status.success(), "unknown base must fail");
    assert!(output.stdout.is_empty(), "no verdict on failure");
}
